#!/usr/bin/env python3
"""vwayland-compositor build + in-package bundling script.

Builds the compositor for one or more target platforms and bundles each into
``src/vwayland/_native/<platform-tag>/``:

- glibc targets: the binary plus its non-standard shared libraries (libpixman,
  libxkbcommon) under ``lib/``, with the RPATH set to ``$ORIGIN/lib``.
- musl targets: a single statically-linked binary (no bundled libs needed).

The native (host) build only needs cargo + patchelf. Cross builds additionally
need a per-target sysroot containing pixman/xkbcommon (headers for glibc,
static libs for musl) and a C cross toolchain; set ``CC_<rust-target>`` /
``CARGO_TARGET_<TRIPLE>_LINKER`` and ``RUSTFLAGS=-L <sysroot>/lib`` in the
environment (see scripts/cross_env.sh, generated by scripts/prepare_sysroots.py).

Usage:
    python3 scripts/build_compositor.py                       # native (host) build
    python3 scripts/build_compositor.py --target aarch64-unknown-linux-gnu
    python3 scripts/build_compositor.py --no-build            # re-bundle only
"""

from __future__ import annotations

import argparse
import os
import re

# readelf/ldd output is parsed with English regexes; force the C locale.
os.environ.setdefault("LC_ALL", "C")
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
NATIVE_DIR = REPO_ROOT / "src" / "vwayland" / "_native"
BINARY_NAME = "vwayland-compositor"

# Rust target triple -> wheel-style platform tag used for the bundle dir.
TARGET_TAGS = {
    "x86_64-unknown-linux-gnu": "manylinux_2_28_x86_64",
    "aarch64-unknown-linux-gnu": "manylinux_2_28_aarch64",
    "riscv64gc-unknown-linux-gnu": "manylinux_2_28_riscv64",
    "x86_64-unknown-linux-musl": "musllinux_1_2_x86_64",
    "aarch64-unknown-linux-musl": "musllinux_1_2_aarch64",
}

# System libraries that are not bundled (glibc/compiler runtime).
SYSTEM_LIBS = (
    "linux-vdso",
    "ld-linux",
    "ld-musl",
    "libc.so",
    "libm.so",
    "libdl.so",
    "librt.so",
    "libpthread.so",
    "libutil.so",
    "libresolv.so",
    "libgcc_s.so",
    "libstdc++.so",
)

LDD_LINE = re.compile(r"^\s*(\S+)\s+=>?\s*(/\S+)?")


def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    print("+", " ".join(str(c) for c in cmd))
    return subprocess.run(cmd, check=True, **kw)


def host_target() -> str:
    """Best-effort Rust host triple detection."""
    out = subprocess.run(
        ["rustc", "-vV"], capture_output=True, text=True, check=True
    ).stdout
    for line in out.splitlines():
        if line.startswith("host:"):
            return line.split(":", 1)[1].strip()
    sys.exit("error: could not detect rustc host triple")


def cargo_build(target: str) -> Path:
    cargo = shutil.which("cargo")
    if not cargo:
        sys.exit("error: cargo not found. Install Rust via https://rustup.rs")
    run([cargo, "build", "--release", "--target", target, "-p", "vwayland-compositor"],
        cwd=REPO_ROOT / "rust")
    binary = REPO_ROOT / "rust" / "target" / target / "release" / BINARY_NAME
    if not binary.is_file():
        sys.exit(f"error: build output missing: {binary}")
    return binary


def ldd_paths(binary: Path) -> list[tuple[str, Path]]:
    out = subprocess.run(
        ["ldd", str(binary)], capture_output=True, text=True, check=True
    ).stdout
    deps: list[tuple[str, Path]] = []
    for line in out.splitlines():
        line = line.strip()
        if "not found" in line:
            sys.exit(f"error: unresolved library: {line}")
        m = LDD_LINE.match(line)
        if not m:
            continue
        name, path = m.group(1), m.group(2)
        if path is None:  # linux-vdso etc.
            continue
        deps.append((name, Path(path)))
    return deps


def needed_libs(binary: Path) -> list[str]:
    """DT_NEEDED entries of a (possibly foreign-arch) dynamic binary."""
    out = subprocess.run(
        ["readelf", "-d", str(binary)], capture_output=True, text=True, check=True
    ).stdout
    return re.findall(r"\(NEEDED\)\s+Shared library: \[(\S+)\]", out)


def resolve_in_sysroot(name: str, search: list[Path]) -> "Path | None":
    for d in search:
        cand = d / name
        if cand.exists():
            return cand
    return None


def is_system_lib(name: str) -> bool:
    return Path(name).name.startswith(SYSTEM_LIBS)


# ELF e_machine -> host platform.machine() it runs on natively.
_ELF_MACHINE = {
    62: {"x86_64", "amd64"},        # EM_X86_64
    183: {"aarch64", "arm64"},      # EM_AARCH64
    243: {"riscv64", "riscv64gc"},  # EM_RISCV
}


def same_arch(binary: Path) -> bool:
    """True if the binary matches the host architecture (ldd works on it)."""
    import platform
    import struct

    try:
        with open(binary, "rb") as f:
            ident = f.read(16)  # e_ident: magic(4) class data version ...
            if ident[:4] != b"\x7fELF":
                return True
            endian = "<" if ident[5] == 1 else ">"  # EI_DATA
            f.seek(18)  # e_machine
            (e_machine,) = struct.unpack(f"{endian}H", f.read(2))
    except (OSError, struct.error):
        return True
    host = platform.machine().lower()
    return host in _ELF_MACHINE.get(e_machine, {host})


def is_static(binary: Path) -> bool:
    # Works for foreign-arch too: static binaries have no PT_INTERP/DT_NEEDED.
    try:
        out = subprocess.run(
            ["readelf", "-d", str(binary)], capture_output=True, text=True, check=True
        ).stdout
    except subprocess.CalledProcessError:
        return True
    return "NEEDED" not in out


def bundle(binary: Path, target: str) -> Path:
    tag = TARGET_TAGS.get(target)
    if tag is None:
        sys.exit(
            f"error: no platform tag known for target {target!r}; "
            f"add it to TARGET_TAGS in {__file__}"
        )
    native_dir = NATIVE_DIR / tag
    lib_dir = native_dir / "lib"
    native_dir.mkdir(parents=True, exist_ok=True)
    dest = native_dir / BINARY_NAME
    shutil.copy2(binary, dest)
    dest.chmod(0o755)
    print(f"copied {binary} -> {dest}")

    if is_static(dest):
        # musl targets: fully static, nothing to bundle.
        if lib_dir.exists():
            shutil.rmtree(lib_dir)
        print(f"static binary; no libs bundled for {tag}")
        return dest

    patchelf = shutil.which("patchelf")
    if not patchelf:
        sys.exit(
            "error: patchelf is required for dynamic (glibc) bundles "
            "(e.g.: sudo apt install patchelf / dnf install patchelf)"
        )
    lib_dir.mkdir(parents=True, exist_ok=True)
    for old in lib_dir.glob("*.so*"):
        old.unlink()

    bundled: list[Path] = []
    if same_arch(dest):
        for name, path in ldd_paths(dest):
            if is_system_lib(name):
                continue
            real = path.resolve()
            target_file = lib_dir / path.name
            shutil.copy2(real, target_file)
            target_file.chmod(0o755)
            bundled.append(target_file)
            print(f"bundled {real} -> {target_file}")
    else:
        # Foreign-arch build: parse DT_NEEDED and resolve from the cross
        # sysroots passed via VWAYLAND_SYSROOT_LIB (os.pathsep-separated).
        search = [Path(p) for p in os.environ.get("VWAYLAND_SYSROOT_LIB", "").split(os.pathsep) if p]
        if not search:
            sys.exit(
                "error: cross (foreign-arch) bundling needs VWAYLAND_SYSROOT_LIB "
                "pointing at the target's sysroot lib dir(s)"
            )
        for name in needed_libs(dest):
            if is_system_lib(name):
                continue
            src_lib = resolve_in_sysroot(name, search)
            if src_lib is None:
                sys.exit(f"error: could not resolve {name} in VWAYLAND_SYSROOT_LIB={search}")
            real = src_lib.resolve()
            target_file = lib_dir / name
            shutil.copy2(real, target_file)
            target_file.chmod(0o755)
            bundled.append(target_file)
            print(f"bundled {real} -> {target_file}")

    if bundled:
        run([patchelf, "--set-rpath", "$ORIGIN/lib", str(dest)])
        for lib in bundled:
            run([patchelf, "--set-rpath", "$ORIGIN", str(lib)])
    else:
        run([patchelf, "--remove-rpath", str(dest)])
    return dest


def verify(dest: Path) -> None:
    print("\n== bundle verification ==")
    if not same_arch(dest):
        # Cannot execute a foreign-arch binary here; check linkage statically.
        libs = needed_libs(dest)
        unresolved = [
            n for n in libs
            if not is_system_lib(n) and not (dest.parent / "lib" / n).exists()
        ]
        if unresolved:
            sys.exit(f"error: foreign bundle missing libs: {unresolved}")
        print(f"foreign-arch bundle; DT_NEEDED: {libs}")
        print("(skipped --version: cannot run a foreign-arch binary natively)")
        return
    if is_static(dest):
        out = subprocess.run(["ldd", str(dest)], capture_output=True, text=True).stdout
        print(out.strip() or "(static)")
    else:
        out = subprocess.run(["ldd", str(dest)], capture_output=True, text=True).stdout
        bad = [
            line.strip()
            for line in out.splitlines()
            if "not found" in line
            or ("=>" in line and not is_system_lib(line.split()[0])
                and "_native" not in line)
        ]
        if bad:
            sys.exit(
                "error: dependencies not resolved by the bundled lib:\n"
                + "\n".join(bad)
            )
        print(out)
    if same_arch(dest):
        version = subprocess.run([str(dest), "--version"], capture_output=True, text=True)
        print(version.stdout.strip() or version.stderr.strip())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--target",
        default=None,
        help="Rust target triple (default: host). Known: "
        + ", ".join(sorted(TARGET_TAGS)),
    )
    ap.add_argument(
        "--no-build",
        action="store_true",
        help="skip cargo build (re-bundle the existing release binary)",
    )
    args = ap.parse_args()
    target = args.target or host_target()

    if args.no_build:
        binary = REPO_ROOT / "rust" / "target" / target / "release" / BINARY_NAME
        if not binary.is_file():
            sys.exit(f"error: {binary} does not exist (run without --no-build)")
    else:
        binary = cargo_build(target)
    dest = bundle(binary, target)
    verify(dest)
    print(f"\ndone: {dest.parent}")


if __name__ == "__main__":
    main()
